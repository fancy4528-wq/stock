"""Markdown factor test reports under docs/factor-reports/."""

from __future__ import annotations

from pathlib import Path

from quantagent.quant.evaluation.types import FactorTestResult


def render_factor_report(result: FactorTestResult) -> str:
    """Render a single-factor markdown report."""
    start, end = result.period
    q_header = " | ".join(f"Q{i}" for i in range(1, result.n_quantiles + 1))
    q_sep = " | ".join("---" for _ in range(result.n_quantiles))
    q_vals = " | ".join(f"{v:+.4%}" for v in result.quantile_returns)
    decay = ", ".join(
        f"{h}d={v:+.4f}" for h, v in zip(result.ic_decay_horizons, result.ic_decay, strict=False)
    )
    years = ", ".join(f"{y}={v:+.4f}" for y, v in sorted(result.ic_by_year.items())) or "(n/a)"
    regimes = ", ".join(f"{k}={v:+.4f}" for k, v in sorted(result.ic_by_regime.items())) or "(n/a)"
    corrs = ", ".join(f"{k}={v:+.3f}" for k, v in sorted(result.correlations.items())) or "(none)"
    notes = "\n".join(f"- {n}" for n in result.admission_notes) or "- (none)"
    status = "PASS" if result.admission_pass else "FAIL"

    return f"""# Factor report: `{result.factor_code}`

> Generated by QuantAgent W6 evaluation | period {start.isoformat()} → {end.isoformat()}
> Horizon: {result.horizon_days}d forward return | Quantiles: {result.n_quantiles}
> Admission: **{status}**

## IC analysis

| Metric | Value |
|---|---|
| IC mean | {result.ic_mean:+.4f} |
| IC std | {result.ic_std:.4f} |
| ICIR | {result.icir:+.4f} |
| IC t-stat | {result.ic_t_stat:+.3f} |
| IC p-value | {result.ic_p_value:.4f} |
| IC > 0 ratio | {result.ic_positive_ratio:.1%} |
| N periods | {result.n_ic_periods} |

## Quantile returns

| {q_header} |
| {q_sep} |
| {q_vals} |

- Monotonicity (Spearman Q vs ret): {result.monotonicity:+.3f}
- Long-short mean return: {result.long_short_return:+.4%}
- Long-short Sharpe (period-scaled): {result.long_short_sharpe:+.3f}

## Stability

- IC decay: {decay or "(n/a)"}
- IC by year: {years}
- IC by regime (mkt up/down): {regimes}
- Factor autocorr (t vs t-1): {result.autocorrelation:+.3f}
- Turnover estimate `1-|ac|`: {result.turnover_estimate:.3f}

## Correlations vs other factors

{corrs}

## Admission checklist

{notes}

---
*Thresholds: |IC|≥0.02, |t|≥2, ICIR≥0.3, directionality outside (0.45,0.55),
year same-sign ≥60%, pairwise |corr|<0.7 (docs/07-quant-engine.md §3.2).*
"""


def write_factor_report(result: FactorTestResult, path: Path | str) -> Path:
    """Write markdown report to ``path`` (parent dirs created)."""
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_factor_report(result), encoding="utf-8")
    return out


def write_factor_reports(
    results: dict[str, FactorTestResult],
    out_dir: Path | str,
) -> list[Path]:
    """Write one markdown file per factor under ``out_dir``."""
    root = Path(out_dir)
    root.mkdir(parents=True, exist_ok=True)
    paths: list[Path] = []
    for code, result in results.items():
        paths.append(write_factor_report(result, root / f"{code}.md"))
    # Index
    lines = [
        "# Factor reports (W6)",
        "",
        "Generated by `make evaluate` or `quantagent.cli evaluate`.",
        "",
        "- Synthetic (no DB): `uv run python -m quantagent.cli evaluate --synthetic`",
        "- From parquet: `... evaluate --panel path.parquet --factors mom_20d,rev_5d`",
        "",
        f"Factors evaluated: {len(results)}",
        "",
        "| Factor | IC mean | ICIR | t | Admission |",
        "|---|---:|---:|---:|:---:|",
    ]
    for code, r in sorted(results.items()):
        lines.append(
            f"| [`{code}`]({code}.md) | {r.ic_mean:+.4f} | {r.icir:+.3f} | "
            f"{r.ic_t_stat:+.2f} | {'PASS' if r.admission_pass else 'FAIL'} |"
        )
    index = root / "README.md"
    index.write_text("\n".join(lines) + "\n", encoding="utf-8")
    paths.append(index)
    return paths
